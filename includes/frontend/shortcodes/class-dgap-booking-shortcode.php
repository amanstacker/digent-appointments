<?php
if ( ! defined( 'ABSPATH' ) ) exit;

class DGAP_Booking_Shortcode {

	private $localize_data = [];

	/**
	 * Register the shortcode
	 */
	public function register() {
		add_shortcode( 'dgap_booking_form', [ $this, 'render_form' ] );
		add_filter( 'dgap_localize_front_data', [ $this, 'localize_front_data' ] );
	}

	/**
	 * Render the booking form
	 */
	public function render_form( $atts = [] ) {        
		
		$atts = shortcode_atts( [ 'id' => 0 ], $atts, 'dgap_booking_form' );
        $id   = absint( $atts['id'] );

        if ( ! $id ) {
            return '<p>' . esc_html__( 'No form ID specified.', 'digent-appointments' ) . '</p>';
        }

        $adv_settings   = get_option( 'dgap_advanced_settings', [] );
        $disable_css    = ! empty( $adv_settings['disable_frontend_css'] );
        $custom_css     = ! empty( $adv_settings['custom_frontend_css'] ) ? wp_strip_all_tags( (string) $adv_settings['custom_frontend_css'] ) : '';

        // enqueue frontend scripts and styles
        if ( ! $disable_css ) {
            wp_enqueue_style('dgap-forms-shared');
            wp_enqueue_style('dgap-frontend');
        }
		wp_enqueue_style('dgap-flatpickr-css');

		wp_enqueue_script('dgap-flatpickr');
		wp_enqueue_script('dgap-frontend');

        if ( '' !== trim( $custom_css ) ) {
            if ( ! $disable_css ) {
                wp_add_inline_style( 'dgap-frontend', $custom_css );
            } else {
                echo '<style id="dgap-custom-frontend-css">' . $custom_css . '</style>'; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- stripped via wp_strip_all_tags
            }
        }

        // Load repos needed for rendering
        require_once DGAP_PLUGIN_DIR_PATH . 'includes/repositories/class-dgap-location-repo.php';
        require_once DGAP_PLUGIN_DIR_PATH . 'includes/repositories/class-dgap-form-repo.php';
        require_once DGAP_PLUGIN_DIR_PATH . 'includes/admin/class-dgap-form-renderer.php';

        $form = DGAP_Form_Repo::get( $id );

        if ( ! $form ) {
            return '<p>' . esc_html__( 'Form not found.', 'digent-appointments' ) . '</p>';
        }

        // Decode stored data
        $form['settings']      = maybe_unserialize( $form['settings'] )      ?: [];
        $form['custom_fields'] = maybe_unserialize( $form['custom_fields'] ) ?: [];

        $adv_settings       = get_option( 'dgap_advanced_settings', [] );
        $gdpr_enabled       = ! empty( $adv_settings['gdpr_enabled'] );
        $form_gdpr_on       = ! isset( $form['settings']['enable_gdpr'] ) || 1 === (int) $form['settings']['enable_gdpr'];
        $gdpr_label         = ! empty( $adv_settings['gdpr_label'] ) ? $adv_settings['gdpr_label'] : __( 'I agree to the storage and handling of my data by this website.', 'digent-appointments' );
        $gdpr_url           = ! empty( $adv_settings['gdpr_privacy_url'] ) ? $adv_settings['gdpr_privacy_url'] : '';

        $recap_enabled      = ! empty( $adv_settings['recaptcha_enabled'] ) && ! empty( $adv_settings['recaptcha_site_key'] );
        $recap_version      = $adv_settings['recaptcha_version'] ?? 'v2';
        $recap_site_key     = $adv_settings['recaptcha_site_key'] ?? '';
        $form_recap_on      = ! isset( $form['settings']['enable_recaptcha'] ) || 1 === (int) $form['settings']['enable_recaptcha'];
        $recap_active       = $recap_enabled && ( 'v3' === $recap_version || $form_recap_on );

        if ( $recap_active ) {
            $recap_src = ( 'v3' === $recap_version )
                ? 'https://www.google.com/recaptcha/api.js?render=' . rawurlencode( $recap_site_key )
                : 'https://www.google.com/recaptcha/api.js?render=explicit';
            wp_enqueue_script( 'dgap-google-recaptcha', $recap_src, [], null, true ); // phpcs:ignore WordPress.WP.EnqueuedResourceParameters.MissingVersion
        }

        $this->localize_data = [
            'id'            => $id,
            'layout'        => $form['layout'],
            'design'        => $form['settings']['design'] ?? 'flat',
            'labels'        => $form['settings']['labels'] ?? [],
            'custom_fields' => array_values( $form['custom_fields'] ),
            'settings' 		=> $form['settings'],
            'gdpr'          => [
                'enabled'     => ( $gdpr_enabled && $form_gdpr_on ),
                'label'       => $gdpr_label,
                'privacy_url' => esc_url_raw( $gdpr_url ),
            ],
            'recaptcha'     => [
                'enabled'  => $recap_active,
                'version'  => $recap_version,
                'site_key' => $recap_site_key,
            ],
        ];

        ob_start();        
        echo '<div class="dgap-form-wrap" data-form-id="' . esc_attr( $id ) . '">';        
        echo DGAP_Form_Renderer::render( $form ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- HTML is generated by our own renderer with proper escaping inside
        echo '</div>';
        return ob_get_clean();

	}

	public function localize_front_data( $localize = [] ) {
		
		if ( ! empty( $this->localize_data ) ) {
			$localize 	=	$this->localize_data;
		}

		return $localize;

	}

}